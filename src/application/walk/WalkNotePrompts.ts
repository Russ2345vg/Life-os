type QuestionInsertion = {
  readonly status: 'added' | 'alreadyAdded' | 'tooLong';
  readonly text: string;
};

/** Questions stay ordinary note text: no new capture or sync format. */
export function appendWalkNoteQuestion(draft: string, question: string): QuestionInsertion {
  if (draft.split(/\r?\n/u).some((line) => line.trim() === question)) {
    return { status: 'alreadyAdded', text: draft };
  }
  const separator = draft.length === 0 || draft.endsWith('\n\n') ? '' : '\n\n';
  const text = `${draft}${separator}${question}\n`;
  return text.length <= MAX_WALK_CAPTURE_LENGTH
    ? { status: 'added', text }
    : { status: 'tooLong', text: draft };
}
