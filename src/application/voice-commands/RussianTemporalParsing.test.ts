import { describe, expect, it } from 'vitest';
import { DayDate } from '../../domain';
import { extractRussianCommandDate } from './parseRussianCommandDate';
import { parseRussianCommandTime } from './parseRussianCommandTime';

describe('Russian calendar dates', () => {
  it.each([
    ['2026-09-08', 'сегодня', '2026-09-08'],
    ['2026-09-08', 'завтра', '2026-09-09'],
    ['2026-12-31', 'завтра', '2027-01-01'],
    ['2028-02-28', 'послезавтра', '2028-03-01'],
    ['2026-09-08', 'в пятницу', '2026-09-11'],
    ['2026-09-11', 'в пятницу', '2026-09-11'],
    ['2026-09-12', 'в пятницу', '2026-09-18'],
    ['2026-09-13', 'в следующую пятницу', '2026-09-18'],
    ['2026-09-08', 'через 3 дня', '2026-09-11'],
    ['2026-09-08', 'через 21 день', '2026-09-29'],
    ['2026-09-08', 'через неделю', '2026-09-15'],
    ['2026-12-28', 'через неделю', '2027-01-04'],
    ['2026-09-08', '15 сентября', '2026-09-15'],
    ['2026-09-08', 'первого декабря', '2026-12-01'],
    ['2026-09-08', 'двадцать первого декабря', '2026-12-21'],
    ['2026-09-08', 'тридцать первого декабря', '2026-12-31'],
    ['2026-09-08', '1 декабря', '2026-12-01'],
    ['2026-09-08', '01.12', '2026-12-01'],
    ['2026-09-08', '1.12.2027', '2027-12-01'],
    ['2026-09-08', '2027-12-01', '2027-12-01'],
    ['2026-12-20', '1 декабря', '2026-12-01'],
    ['2026-09-08', 'вчера', '2026-09-07'],
  ])('%s + %s = %s without silent year rollover', (current, date, value) => {
    for (const body of [`${date} купить хлеб`, `купить ${date} хлеб`, `купить хлеб ${date}`])
      expect(extractRussianCommandDate(body, DayDate.create(current))).toEqual({
        title: 'купить хлеб',
        value,
      });
  });
  it.each([
    '31 февраля',
    '29 февраля 2026',
    '00.12',
    '12.13',
    'завтра послезавтра',
    'через 0 дней',
    'через 99999 дней',
    '2026-02-30',
  ])('requires clarification for %s', (date) => {
    expect(
      extractRussianCommandDate(`купить хлеб ${date}`, DayDate.create('2026-09-08')).issue,
    ).toBeTruthy();
  });
});
describe('Russian time', () => {
  it.each([
    ['В 10:30', '10:30'],
    ['в 10', '10:00'],
    ['в 10:30', '10:30'],
    ['в десять утра', '10:00'],
    ['в семь вечера', '19:00'],
    ['в 12 дня', '12:00'],
    ['в 12 ночи', '00:00'],
    ['в 00:05', '00:05'],
    ['в двадцать три', '23:00'],
  ])('extracts %s', (time, value) => {
    expect(parseRussianCommandTime(`купить хлеб ${time}`)).toEqual({ title: 'купить хлеб', value });
  });
  it.each([
    'утром',
    'днём',
    'вечером',
    'ночью',
    'в 25',
    'в 10:99',
    'в 10 в 11',
    'в 10 или в 11',
    'в 10:3',
    'в десять тридцать',
  ])('does not guess a time for %s', (time) => {
    expect(parseRussianCommandTime(`купить хлеб ${time}`).issue).toBeTruthy();
  });
});
